<h2>Коли замовлення анулюють</h2>
<p>Навіть після оплати замовлення може отримати статус «Анульовано». Правила (п. 63, 72) називають такі причини:</p>
<ul>
<li>помилка платіжної системи чи сервісу або технічний збій;</li>
<li>перевищення ліміту;</li>
<li>дублювання персональних даних;</li>
<li>чужі особисті дані або вигадане ім’я.</li>
</ul>
<p>Причину НБУ вказує в листі на вашу пошту, а гроші повертає на ту саму картку чи рахунок, з якого платили. Скільки триває повернення, залежить від банку-емітента (п. 73, 74).</p>
