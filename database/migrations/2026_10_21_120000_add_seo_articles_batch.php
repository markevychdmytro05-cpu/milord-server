<p>Список перевізників магазин показує на сайті (п. 78). За повідомленням <a href="https://bank.gov.ua/ua/news/all/internet-magazin-numizmatichnoyi-produktsiyi-natsionalnogo-banku-vidnovlyuye-robotu">НБУ</a>, замовлення доставляють «Нова пошта» та «Укрпошта». Доставки немає на тимчасово окуповані території, на адреси військових частин та інших об’єктів з особливим режимом допуску, установ виконання покарань, слідчих ізоляторів і на абонентські поштові скриньки (п. 39 Договору, додаток 1 до Правил).</p>
<h2>Ліміти на кількість</h2>
<p>НБУ має право встановлювати ліміт замовлення на одного покупця, щоб регулювати попит і розподіляти монети між покупцями (п. 6, 30). Ліміт обов’язковий: його не можна ні перевищувати, ні обходити, інакше НБУ може заблокувати акаунт чи анулювати замовлення (п. 31).</p>
<p>Скільки штук можна взяти, залежить від товару. Наприклад, для срібної інвестиційної монети «Архістратиг Михаїл» номіналом 1 грн на початку жовтня 2026 року НБУ повідомляв про ліміт 20 штук на покупця, як <a href="https://www.obozrevatel.com/ukr/section-ekonomika-glavnaya/economy/news-nbu-vydaye-ukrayintsyam-sribni-monety-nominalom-1-hrn-z-osoblyvym-dyzaynom-skilky-mozhna-otrymaty-za-odyn-raz-01-10-2026.html">передав «Обозреватель»</a>.</p>
